"""The guided upgrade validates versions and edits only what it owns.

These tests cover the pure planning and file-editing helpers. They never run a
container, take a backup or touch the host.
"""

from __future__ import annotations

import importlib.util
import json
import stat
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

SPEC = importlib.util.spec_from_file_location(
    "patchtrack_upgrader", ROOT / "scripts" / "patchtrack_upgrade.py"
)
assert SPEC and SPEC.loader
upgrader = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = upgrader
SPEC.loader.exec_module(upgrader)


def write_manifest(tmp_path, **overrides):
    config = tmp_path / "etc" / "patchtrack"
    install = tmp_path / "opt" / "patchtrack"
    secrets = config / "secrets"
    secrets.mkdir(parents=True)
    install.mkdir(parents=True)
    data = {
        "config_dir": str(config),
        "install_dir": str(install),
        "secrets_dir": str(secrets),
        "runtime": "docker",
        "version": "3.0.0",
        "image": "patchtrack:3.0.0",
        "service_user": "patchtrack",
        "compose_project": "patchtrack",
    }
    data.update(overrides)
    (config / "install.json").write_text(json.dumps(data))
    (config / ".env").write_text(
        "# generated by install.sh\n"
        "PATCHTRACK_TLS_ENABLED=true\n"
        "PATCHTRACK_VERSION=3.0.0\n"
        "PATCHTRACK_GATEWAY_PORT=8005\n"
    )
    return config


def test_upgrade_version_must_change_and_cannot_downgrade():
    assert upgrader.validate_upgrade_version("3.0.0", "3.1.0") is None
    assert "required" in upgrader.validate_upgrade_version("3.0.0", "")
    assert "already at 3.0.0" in upgrader.validate_upgrade_version("3.0.0", "3.0.0")
    assert "older" in upgrader.validate_upgrade_version("3.1.0", "3.0.9")
    assert "must start with a digit" in upgrader.validate_upgrade_version(
        "3.0.0", "v3.1.0"
    )


def test_version_key_compares_numeric_parts():
    assert upgrader.version_key("3.1.0") == (3, 1, 0)
    assert upgrader.version_key("3.10.0") > upgrader.version_key("3.9.9")


def test_env_version_is_replaced_in_place_preserving_mode_and_other_lines(tmp_path):
    env = tmp_path / ".env"
    env.write_text(
        "# keep this comment\n"
        "PATCHTRACK_TLS_ENABLED=true\n"
        "PATCHTRACK_VERSION=3.0.0\n"
        "PATCHTRACK_GATEWAY_PORT=8005\n"
    )
    env.chmod(0o640)

    upgrader.replace_env_version(env, "3.1.0")

    text = env.read_text()
    assert "PATCHTRACK_VERSION=3.1.0" in text
    assert "PATCHTRACK_VERSION=3.0.0" not in text
    assert "PATCHTRACK_TLS_ENABLED=true" in text
    assert "# keep this comment" in text
    assert stat.S_IMODE(env.stat().st_mode) == 0o640


def test_env_version_is_appended_when_the_installer_did_not_write_it(tmp_path):
    env = tmp_path / ".env"
    env.write_text("PATCHTRACK_TLS_ENABLED=true\n")

    upgrader.replace_env_version(env, "3.1.0")

    assert env.read_text().endswith("PATCHTRACK_VERSION=3.1.0\n")


def test_read_env_ignores_comments_and_unquotes_values(tmp_path):
    env = tmp_path / ".env"
    env.write_text(
        "# HTTP_PROXY=http://ignored:1\n"
        "HTTPS_PROXY='http://user:secret@proxy.example:3128'\n"
        "NO_PROXY=localhost,postgres\n"
        "MALFORMED\n"
    )

    values = upgrader.read_env(env)

    assert values["HTTPS_PROXY"] == "http://user:secret@proxy.example:3128"
    assert values["NO_PROXY"] == "localhost,postgres"
    assert "MALFORMED" not in values


def test_probe_url_uses_the_bind_address_and_tls_setting(tmp_path):
    config = write_manifest(tmp_path)
    (config / ".env").write_text(
        "PATCHTRACK_TLS_ENABLED=true\n"
        "PATCHTRACK_BIND_ADDRESS=0.0.0.0\n"
        "PATCHTRACK_GATEWAY_PORT=9443\n"
    )
    manifest = upgrader.manifest_reader.load_manifest(config / "install.json")

    assert upgrader.probe_url(manifest) == "https://127.0.0.1:9443"

    (config / ".env").write_text(
        "PATCHTRACK_TLS_ENABLED=false\n"
        "PATCHTRACK_BIND_ADDRESS=192.0.2.10\n"
        "PATCHTRACK_GATEWAY_PORT=8080\n"
    )
    assert upgrader.probe_url(manifest) == "http://192.0.2.10:8080"


def test_backup_must_not_live_inside_the_application_tree(tmp_path):
    config = write_manifest(tmp_path)
    args = SimpleNamespace(
        config_dir=config,
        source_dir=ROOT,
        backup_dir=tmp_path / "opt" / "patchtrack" / "backups",
        version="3.1.0",
    )

    with pytest.raises(upgrader.UpgradeError, match="backup directory"):
        upgrader.build_context(args)


def test_staging_paths_sit_beside_the_installed_tree(tmp_path):
    install = tmp_path / "opt" / "patchtrack"
    staging, previous = upgrader.staging_paths(install)

    assert staging.parent == install.parent
    assert previous.parent == install.parent
    assert staging.name == "patchtrack.upgrade-new"
    assert previous.name == "patchtrack.upgrade-old"


def test_upgrade_help_is_safe_to_run_without_root():
    import subprocess

    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "patchtrack_upgrade.py"), "--help"],
        capture_output=True, text=True, check=False,
    )

    assert result.returncode == 0
    assert "--check" in result.stdout
    assert "--version" in result.stdout
    assert "--backup-dir" in result.stdout
